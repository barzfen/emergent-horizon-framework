def restrict_representation_set(
    block_basis: sp.Matrix,
    representations: Mapping[Permutation, sp.Matrix],
    f7,
) -> Dict[Permutation, sp.Matrix]:
    workspace = f7.restriction_workspace(block_basis)
    return {
        element: f7.restriction_matrix_cached(
            matrix, block_basis, workspace
        )
        for element, matrix in representations.items()
    }


def block_character_data(
    block_basis: sp.Matrix,
    classes: Sequence[Sequence[Permutation]],
    representations: Mapping[Permutation, sp.Matrix],
    group_ops,
    f7,
) -> Tuple[List[sp.Rational], List[int], List[int | None]]:
    workspace = f7.restriction_workspace(block_basis)
    _, traces, fixed, anti = f7.sector_class_character_data(
        block_basis, classes, representations, group_ops, workspace
    )
    return traces, fixed, anti


def character_norm_from_classes(
    classes: Sequence[Sequence[Permutation]],
    traces: Sequence[sp.Rational],
    group_order: int,
) -> sp.Rational:
    return sp.Rational(
        sum(len(cell) * trace * trace for cell, trace in zip(classes, traces)),
        group_order,
    )


def integer_coordinate_rows(matrix: sp.Matrix, f7) -> List[List[int]]:
    return [
        f7.primitive_integer_row([matrix[row, column] for column in range(matrix.cols)])
        for row in range(matrix.rows)
    ]


def support_summary(
    coordinate_rows: Sequence[Sequence[int]],
    orbits: Sequence[Sequence[int]],
) -> dict:
    dimension = len(coordinate_rows)
    coordinate_count = len(coordinate_rows[0]) if coordinate_rows else 0
    active = [
        any(coordinate_rows[row][column] != 0 for row in range(dimension))
        for column in range(coordinate_count)
    ]
    orbit_activity = [sum(active[column] for column in orbit) for orbit in orbits]
    union_exact = all(count in {0, len(orbit)} for count, orbit in zip(orbit_activity, orbits))
    support_sizes = [sum(value != 0 for value in row) for row in coordinate_rows]
    return {
        "coordinate_count": coordinate_count,
        "active_coordinate_count": sum(active),
        "forced_zero_coordinate_count": coordinate_count - sum(active),
        "full_coordinate_support": all(active),
        "automorphism_orbit_count": len(orbits),
        "active_automorphism_orbit_count": sum(count > 0 for count in orbit_activity),
        "support_is_union_of_automorphism_orbits": union_exact,
        "entire_block_supported_on_one_orbit": sum(count > 0 for count in orbit_activity) == 1,
        "canonical_basis_support_min": min(support_sizes, default=0),
        "canonical_basis_support_max": max(support_sizes, default=0),
        "canonical_basis_support_mean": fraction_text(
            sp.Rational(sum(support_sizes), len(support_sizes)) if support_sizes else 0
        ),
    }


def class_character_hash(
    literal_group_hash: str,
    traces: Sequence[sp.Rational],
) -> str:
    return stable_json_hash({
        "literal_group_hash": literal_group_hash,
        "class_character": [fraction_text(value) for value in traces],
    })


def order_trace_histogram(
    classes: Sequence[Sequence[Permutation]],
    traces: Sequence[sp.Rational],
    group_ops,
) -> str:
    counter: Counter = Counter()
    for cell, trace in zip(classes, traces):
        counter[(group_ops.permutation_order(cell[0]), fraction_text(trace))] += len(cell)
    return ";".join(
        f"o{order}:t{trace}:n{count}"
        for (order, trace), count in sorted(counter.items())
    )


