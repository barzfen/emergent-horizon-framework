def standard_matrix_units(dimension: int) -> List[sp.Matrix]:
    result: List[sp.Matrix] = []
    for row in range(dimension):
        for column in range(dimension):
            matrix = sp.zeros(dimension)
            matrix[row, column] = 1
            result.append(matrix)
    return result


def commutant_basis(generator_matrices: Sequence[sp.Matrix]) -> List[sp.Matrix]:
    if not generator_matrices:
        raise ValueError("at least one generator matrix is required")
    dimension = generator_matrices[0].rows
    if any(matrix.shape != (dimension, dimension) for matrix in generator_matrices):
        raise ValueError("generator dimensions do not agree")

    if all(scalar_matrix_value(matrix) is not None for matrix in generator_matrices):
        return standard_matrix_units(dimension)

    variable_count = dimension * dimension
    equation_entries: Dict[Tuple[int, int], sp.Rational] = {}
    equation_index = 0
    for representation in generator_matrices:
        for row in range(dimension):
            for column in range(dimension):
                coefficients: Dict[int, sp.Rational] = defaultdict(lambda: sp.Rational(0))
                for middle in range(dimension):
                    right_value = sp.Rational(representation[middle, column])
                    if right_value:
                        coefficients[row * dimension + middle] += right_value
                    left_value = sp.Rational(representation[row, middle])
                    if left_value:
                        coefficients[middle * dimension + column] -= left_value
                nonzero = {index: value for index, value in coefficients.items() if value}
                if not nonzero:
                    continue
                for index, value in nonzero.items():
                    equation_entries[(equation_index, index)] = value
                equation_index += 1

    if equation_index == 0:
        return standard_matrix_units(dimension)

    equations = sp.MutableSparseMatrix(equation_index, variable_count, equation_entries)
    null_rows = DomainMatrix.from_Matrix(equations).nullspace().to_Matrix()
    basis: List[sp.Matrix] = []
    for basis_index in range(null_rows.rows):
        values = [sp.Rational(null_rows[basis_index, index]) for index in range(variable_count)]
        basis.append(sp.Matrix(dimension, dimension, values))
    basis.sort(key=matrix_hash)
    if not basis:
        raise ArithmeticError("commutant unexpectedly vanished")
    return basis


def matrices_commute(left: sp.Matrix, right: sp.Matrix) -> bool:
    return left * right == right * left


def commutant_exact(
    basis: Sequence[sp.Matrix],
    generators: Sequence[sp.Matrix],
) -> bool:
    return all(matrices_commute(item, generator) for item in basis for generator in generators)


def algebra_center_basis(algebra_basis: Sequence[sp.Matrix]) -> List[sp.Matrix]:
    if not algebra_basis:
        return []
    if len(algebra_basis) == 1:
        return [algebra_basis[0]]
    if all(
        matrices_commute(algebra_basis[i], algebra_basis[j])
        for i in range(len(algebra_basis))
        for j in range(i + 1, len(algebra_basis))
    ):
        return list(algebra_basis)

    dimension = algebra_basis[0].rows
    algebra_dimension = len(algebra_basis)
    rows: List[List[sp.Rational]] = []
    for right in algebra_basis:
        commutators = [left * right - right * left for left in algebra_basis]
        for row in range(dimension):
            for column in range(dimension):
                coefficients = [sp.Rational(item[row, column]) for item in commutators]
                if any(coefficients):
                    rows.append(coefficients)
    equation_matrix = sp.Matrix(rows) if rows else sp.zeros(0, algebra_dimension)
    if equation_matrix.rows == 0:
        return list(algebra_basis)
    null_rows = DomainMatrix.from_Matrix(equation_matrix).nullspace().to_Matrix()
    result: List[sp.Matrix] = []
    for basis_index in range(null_rows.rows):
        matrix = sp.zeros(dimension)
        for coefficient_index, source in enumerate(algebra_basis):
            matrix += sp.Rational(null_rows[basis_index, coefficient_index]) * source
        result.append(matrix)
    result.sort(key=matrix_hash)
    return result


def deterministic_algebra_candidates(
    algebra_basis: Sequence[sp.Matrix],
    combination_bound: int,
    candidate_limit: int,
) -> List[Tuple[sp.Matrix, str]]:
    if not algebra_basis:
        return []
    dimension = algebra_basis[0].rows
    identity = sp.eye(dimension)
    candidates: List[Tuple[sp.Matrix, str]] = []
    seen: Set[str] = set()

    def add(matrix: sp.Matrix, description: str) -> None:
        if len(candidates) >= candidate_limit or matrix == sp.zeros(dimension):
            return
        digest = matrix_hash(matrix)
        if digest in seen:
            return
        seen.add(digest)
        candidates.append((matrix, description))

    add(identity, "identity")
    for index, matrix in enumerate(algebra_basis):
        add(matrix, f"basis[{index}]")
        traceless = dimension * matrix - sp.trace(matrix) * identity
        add(traceless, f"traceless_basis[{index}]")

    coefficient_values = [value for value in range(-combination_bound, combination_bound + 1) if value]
    pair_cap = min(len(algebra_basis), 40)
    for left_index in range(pair_cap):
        for right_index in range(left_index + 1, pair_cap):
            left = algebra_basis[left_index]
            right = algebra_basis[right_index]
            for coefficient in coefficient_values:
                add(left + coefficient * right, f"basis[{left_index}]+{coefficient}*basis[{right_index}]")
                if len(candidates) >= candidate_limit:
                    return candidates

    product_cap = min(len(algebra_basis), 24)
    for left_index in range(product_cap):
        for right_index in range(product_cap):
            add(
                algebra_basis[left_index] * algebra_basis[right_index],
                f"basis_product[{left_index},{right_index}]",
            )
            if len(candidates) >= candidate_limit:
                return candidates

    if combination_bound >= 2:
        triple_cap = min(len(algebra_basis), 16)
        for first, second, third in itertools.combinations(range(triple_cap), 3):
            add(
                algebra_basis[first] + algebra_basis[second] + algebra_basis[third],
                f"basis_sum[{first},{second},{third}]",
            )
            if len(candidates) >= candidate_limit:
                return candidates
    return candidates


def find_singular_commutant_element(
    algebra_basis: Sequence[sp.Matrix],
    combination_bound: int,
    candidate_limit: int,
) -> Tuple[sp.Matrix | None, dict]:
    if not algebra_basis:
        return None, {"candidates_tested": 0, "candidate_description": "", "candidate_rank": ""}
    dimension = algebra_basis[0].rows
    tested = 0
    for candidate, description in deterministic_algebra_candidates(
        algebra_basis, combination_bound, candidate_limit
    ):
        if candidate == sp.zeros(dimension):
            continue
        tested += 1
        rank = exact_rank(candidate)
        if 0 < rank < dimension:
            return candidate, {
                "candidates_tested": tested,
                "candidate_description": description,
                "candidate_rank": rank,
                "candidate_sha256": matrix_hash(candidate),
            }
    return None, {
        "candidates_tested": tested,
        "candidate_description": "",
        "candidate_rank": "",
        "candidate_sha256": "",
    }


def equivariant_projection_onto(
    invariant_subspace: sp.Matrix,
    algebra_basis: Sequence[sp.Matrix],
) -> sp.Matrix:
    """Solve the exact G-equivariant projection onto an invariant subspace.

    P U = U and N P = 0, where rows of N annihilate U.  These conditions are
    linear in the commutant coefficients.  They imply im(P)=U and P^2=P.
    """
    dimension = algebra_basis[0].rows
    subspace = independent_column_basis(invariant_subspace)
    subspace_dimension = subspace.cols
    if not 0 < subspace_dimension < dimension:
        raise ValueError("projection target must be proper and nonzero")

    annihilator_columns = subspace.T.nullspace()
    annihilator = (
        sp.Matrix.vstack(*(column.T for column in annihilator_columns))
        if annihilator_columns
        else sp.zeros(0, dimension)
    )

    equation_rows: List[List[sp.Rational]] = []
    targets: List[sp.Rational] = []
    products_on_subspace = [basis * subspace for basis in algebra_basis]
    for row in range(dimension):
        for column in range(subspace_dimension):
            equation_rows.append([
                sp.Rational(product[row, column])
                for product in products_on_subspace
            ])
            targets.append(sp.Rational(subspace[row, column]))

    annihilator_products = [annihilator * basis for basis in algebra_basis]
    for row in range(annihilator.rows):
        for column in range(dimension):
            equation_rows.append([
                sp.Rational(product[row, column])
                for product in annihilator_products
            ])
            targets.append(sp.Rational(0))

    equations = sp.Matrix(equation_rows)
    target = sp.Matrix(targets)
    coefficients = solve_exact_linear_system(equations, target)
    if coefficients is None:
        raise ArithmeticError("failed to find the Maschke projection")
    projection = sp.zeros(dimension)
    for coefficient, basis in zip(coefficients, algebra_basis):
        projection += coefficient * basis

    if projection * subspace != subspace:
        raise ArithmeticError("projection is not identity on its target")
    if annihilator * projection != sp.zeros(annihilator.rows, dimension):
        raise ArithmeticError("projection image is not contained in target")
    if projection * projection != projection:
        raise ArithmeticError("equivariant projection is not idempotent")
    if exact_rank(projection) != subspace_dimension:
        raise ArithmeticError("projection rank mismatch")
    return projection


def minimal_polynomial_exact(matrix: sp.Matrix) -> sp.Poly:
    if matrix.rows != matrix.cols:
        raise ValueError("minimal polynomial requires a square matrix")
    dimension = matrix.rows
    variable = sp.Symbol("x")
    powers = [sp.eye(dimension)]
    vector_columns = [matrix_vector(powers[0])]
    for degree in range(1, dimension + 1):
        powers.append(powers[-1] * matrix)
        current_vector = matrix_vector(powers[-1])
        previous = sp.Matrix.hstack(*vector_columns)
        if exact_rank(previous.row_join(current_vector)) == exact_rank(previous):
            coefficients = solve_exact_linear_system(previous, -current_vector)
            if coefficients is None:
                raise ArithmeticError("minimal-polynomial dependence solve failed")
            expression = variable ** degree
            for exponent, coefficient in enumerate(coefficients):
                expression += coefficient * variable ** exponent
            polynomial = sp.Poly(expression, variable, domain=sp.QQ)
            # Direct exact verification.
            evaluated = sp.zeros(dimension)
            for coefficient in polynomial.all_coeffs():
                evaluated = evaluated * matrix + sp.Rational(coefficient) * sp.eye(dimension)
            if evaluated != sp.zeros(dimension):
                raise ArithmeticError("minimal-polynomial verification failed")
            return polynomial
        vector_columns.append(current_vector)
    raise ArithmeticError("minimal polynomial not found before Cayley-Hamilton bound")


def commutant_field_certificate(
    algebra_basis: Sequence[sp.Matrix],
    combination_bound: int,
    candidate_limit: int,
) -> dict:
    algebra_dimension = len(algebra_basis)
    if algebra_dimension == 1:
        return {
            "certified": True,
            "generator_description": "scalar_identity",
            "minimal_polynomial": "x",
            "field_degree": 1,
            "candidates_tested": 0,
        }
    if not all(
        matrices_commute(algebra_basis[i], algebra_basis[j])
        for i in range(algebra_dimension)
        for j in range(i + 1, algebra_dimension)
    ):
        return {
            "certified": False,
            "generator_description": "",
            "minimal_polynomial": "",
            "field_degree": "",
            "candidates_tested": 0,
        }
    matrix_dimension = algebra_basis[0].rows
    if algebra_dimension > matrix_dimension:
        return {
            "certified": False,
            "generator_description": "",
            "minimal_polynomial": "",
            "field_degree": "",
            "candidates_tested": 0,
        }

    tested = 0
    for candidate, description in deterministic_algebra_candidates(
        algebra_basis, combination_bound, candidate_limit
    ):
        if candidate == sp.zeros(matrix_dimension):
            continue
        tested += 1
        polynomial = minimal_polynomial_exact(candidate)
        if polynomial.degree() != algebra_dimension:
            continue
        if polynomial.is_irreducible:
            powers = [sp.eye(matrix_dimension)]
            for _ in range(1, algebra_dimension):
                powers.append(powers[-1] * candidate)
            power_rank = exact_rank(sp.Matrix.hstack(*(matrix_vector(item) for item in powers)))
            if power_rank != algebra_dimension:
                continue
            return {
                "certified": True,
                "generator_description": description,
                "minimal_polynomial": str(polynomial.as_expr()),
                "field_degree": algebra_dimension,
                "candidates_tested": tested,
            }
    return {
        "certified": False,
        "generator_description": "",
        "minimal_polynomial": "",
        "field_degree": "",
        "candidates_tested": tested,
    }


