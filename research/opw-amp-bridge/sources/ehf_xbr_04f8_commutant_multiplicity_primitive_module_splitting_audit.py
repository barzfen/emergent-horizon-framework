def self_test() -> None:
    # Scalar three-copy module: full M_3(Q) commutant and immediate 1D split.
    scalar_generator = -sp.eye(3)
    scalar_commutant = commutant_basis([scalar_generator])
    assert len(scalar_commutant) == 9
    assert commutant_exact(scalar_commutant, [scalar_generator])
    assert len(algebra_center_basis(scalar_commutant)) == 1
    singular, info = find_singular_commutant_element(scalar_commutant, 2, 200)
    assert singular is not None and 0 < exact_rank(singular) < 3
    assert info["candidates_tested"] >= 1

    # Rational irreducible C3 module Q(zeta_3), whose commutant is a quadratic
    # field and whose complex character norm is 2.
    c3 = sp.Matrix([[0, -1], [1, -1]])
    field_commutant = commutant_basis([c3])
    assert len(field_commutant) == 2
    assert len(algebra_center_basis(field_commutant)) == 2
    field_certificate = commutant_field_certificate(field_commutant, 2, 200)
    assert field_certificate["certified"]
    assert field_certificate["field_degree"] == 2

    # Two copies of the rational C3 irreducible: M_2(Q(zeta_3)) has dimension 8.
    doubled = sp.diag(1, 1, 1, 1)
    doubled[:2, :2] = c3
    doubled[2:, 2:] = c3
    doubled_commutant = commutant_basis([doubled])
    assert len(doubled_commutant) == 8
    singular, _ = find_singular_commutant_element(doubled_commutant, 2, 1000)
    assert singular is not None
    image_columns = singular.columnspace()
    image = independent_column_basis(sp.Matrix.hstack(*image_columns))
    assert image.cols == 2
    projection = equivariant_projection_onto(image, doubled_commutant)
    assert projection * projection == projection
    complement_columns = projection.nullspace()
    complement = independent_column_basis(sp.Matrix.hstack(*complement_columns))
    assert complement.cols == 2
    assert exact_rank(sp.Matrix.hstack(image, complement)) == 4

    # Minimal polynomial certificate itself.
    polynomial = minimal_polynomial_exact(c3)
    assert polynomial.degree() == 2 and polynomial.is_irreducible

    print("EHF-XBR-04F8 self-test PASS")


