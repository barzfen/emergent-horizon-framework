#!/usr/bin/env python3
"""
EHF-XBR-04B
===========
Cross-Prime Ledger Identity and Rational Certification

XBR-04 computed the minimal OPW-adjacency Krylov closure generated by the
canonical deletion-adjoint AMP lift over one or more finite fields.

XBR-04B has two jobs.

1. Cross-prime ledger identity

   Compare complete XBR-04 run directories and verify, channel by channel and
   depth by depth, that the modular rank-growth ledgers are identical across
   all audited primes.

2. Exact rational certification

   Reconstruct the integer Krylov matrices for each channel and compute exact
   characteristic-zero ranks:

       rank_Q K_(d-1),
       rank_Q K_d,
       rank_Q K_(d+1),

   where d is the modular stabilization depth.

   If

       rank_Q K_(d-1) < r,
       rank_Q K_d = r,
       rank_Q K_(d+1) = r,

   then the rational closure dimension is exactly r and the first rational
   stabilization depth is exactly d.

The recommended exact backend is python-flint's fmpz_mat.rank(), which computes
the rank of an integer matrix exactly. A SymPy fallback is included but can be
much slower for the largest channels.
"""

